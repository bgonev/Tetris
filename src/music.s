.area _CODE

.globl _music_init
.globl _music_init_troika
.globl _music_play_frame
.globl _music_stop
.globl _sfx_line_clear
.globl _firmware_set_mode0

_firmware_set_mode0::
   push ix
   push iy
   xor a
   call 0xBC0E
   pop iy
   pop ix
   ret

_music_init::
   xor a
   ld (music_timer), a
   ld (music_duration), a
   ld (music_index), a
   ld (music_mode), a
   ld (sfx_timer), a
   jp ay_silence

_music_init_troika::
   xor a
   ld (music_timer), a
   ld (music_duration), a
   ld (music_index), a
   ld (sfx_timer), a
   inc a
   ld (music_mode), a
   jp ay_silence

_music_stop::
   xor a
   ld (music_timer), a
   ld (music_duration), a
   ld (sfx_timer), a
   jp ay_silence

_sfx_line_clear::
   ld a, #4
   ld (sfx_timer), a
   ld d, #6
   ld e, #4
   call ay_write
   ld d, #7
   ld e, #0x1C
   call ay_write
   ld d, #10
   ld e, #15
   jp ay_write

_music_play_frame::
   ld a, (music_timer)
   or a
   call z, music_load_note
   call music_render_frame
   ld a, (music_timer)
   or a
   jr z, music_sfx_countdown
   dec a
   ld (music_timer), a
music_sfx_countdown:
   ld a, (sfx_timer)
   or a
   ret z
   dec a
   ld (sfx_timer), a
   ret

music_load_note:
   ld a, (music_index)
   ld e, a
   ld d, #0
   ld l, a
   ld h, #0
   add hl, hl
   add hl, hl
   add hl, hl
   or a
   sbc hl, de
   ld a, (music_mode)
   or a
   jr nz, music_use_troika
   ld de, #korobeiniki_data
   jr music_add_data_base
music_use_troika:
   ld de, #troika_data
music_add_data_base:
   add hl, de

   ld a, (hl)
   ld (music_period_a), a
   inc hl
   ld a, (hl)
   ld (music_period_a+1), a
   inc hl
   ld a, (hl)
   ld (music_period_b), a
   inc hl
   ld a, (hl)
   ld (music_period_b+1), a
   inc hl
   ld a, (hl)
   ld (music_period_c), a
   inc hl
   ld a, (hl)
   ld (music_period_c+1), a
   inc hl
   ld a, (hl)
   or a
   jr nz, music_note_loaded
   ld (music_index), a
   jr music_load_note
music_note_loaded:
   ld (music_timer), a
   ld (music_duration), a
   ld a, (music_index)
   inc a
   ld (music_index), a
   ret

music_render_frame:
   ld d, #0
   ld a, (music_period_a)
   ld e, a
   call ay_write
   ld d, #1
   ld a, (music_period_a+1)
   and #0x0F
   ld e, a
   call ay_write
   ld d, #2
   ld a, (music_period_b)
   ld e, a
   call ay_write
   ld d, #3
   ld a, (music_period_b+1)
   and #0x0F
   ld e, a
   call ay_write
   ld d, #4
   ld a, (music_period_c)
   ld e, a
   call ay_write
   ld d, #5
   ld a, (music_period_c+1)
   and #0x0F
   ld e, a
   call ay_write

   ld a, (sfx_timer)
   or a
   jr z, music_no_sfx
   ld d, #6
   ld e, a
   call ay_write
   ld d, #7
   ld e, #0x1C
   call ay_write
   jr music_write_volumes
music_no_sfx:
   ld d, #6
   ld e, #0x1F
   call ay_write
   ld d, #7
   ld e, #0x38
   call ay_write

music_write_volumes:
   ld a, (music_period_a)
   ld b, a
   ld a, (music_period_a+1)
   or b
   jr z, music_silence_music_channels
   call music_release_gate
   jr c, music_silence_music_channels
   ld d, #8
   ld e, #12
   call ay_write
   ld d, #9
   ld e, #8
   call ay_write
   ld d, #10
   ld a, (sfx_timer)
   or a
   jr z, music_c_volume
   ld e, #15
   jr music_write_c_volume
music_c_volume:
   ld e, #6
music_write_c_volume:
   call ay_write
   ret

music_silence_music_channels:
   ld d, #8
   ld e, #0
   call ay_write
   ld d, #9
   ld e, #0
   call ay_write
   ld d, #10
   ld a, (sfx_timer)
   or a
   jr z, music_silence_c
   ld e, #15
   jr music_silence_write_c
music_silence_c:
   ld e, #0
music_silence_write_c:
   call ay_write
   ret

music_release_gate:
   ld a, (music_duration)
   cp #80
   jr nc, music_release_8
   cp #40
   jr nc, music_release_4
   cp #30
   jr nc, music_release_3
   cp #20
   jr nc, music_release_2
   ld b, #1
   jr music_release_check
music_release_8:
   ld b, #8
   jr music_release_check
music_release_4:
   ld b, #4
   jr music_release_check
music_release_3:
   ld b, #3
   jr music_release_check
music_release_2:
   ld b, #2
music_release_check:
   ld a, (music_timer)
   cp b
   jr c, music_release_yes
   jr z, music_release_yes
   or a
   ret
music_release_yes:
   scf
   ret

ay_silence:
   ld d, #8
   ld e, #0
   call ay_write
   ld d, #9
   ld e, #0
   call ay_write
   ld d, #10
   ld e, #0
   call ay_write
   ld d, #7
   ld e, #0x3F
   jp ay_write

ay_write:
   push af
   push bc
   ld bc, #0xF782
   out (c), c
   ld b, #0xF4
   out (c), d
   ld bc, #0xF6C0
   out (c), c
   xor a
   out (c), a
   ld b, #0xF4
   out (c), e
   ld bc, #0xF680
   out (c), c
   xor a
   out (c), a
   pop bc
   pop af
   ret
